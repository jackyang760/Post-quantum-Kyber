/*************************************************
* Name:        fqmul
*
* Description: Multiplication followed by Montgomery reduction
*
* Arguments:   - int16_t a: first factor
*              - int16_t b: second factor
*
* Returns 16-bit integer congruent to a*b*R^{-1} mod q
**************************************************/
static int16_t fqmul(int16_t a, int16_t b) {
  return montgomery_reduce((int32_t)a*b);
}

/*************************************************
* Name:        ntt
*
* Description: Inplace number-theoretic transform (NTT) in Rq.
*              input is in standard order, output is in bitreversed order
*
* Arguments:   - int16_t r[256]: pointer to input/output vector of elements of Zq
**************************************************/
void ntt(int16_t r[256]) {
  unsigned int len, start, j, k;
  int16_t t, zeta;

  k = 1;
  for(len = 128; len >= 2; len >>= 1) {
    for(start = 0; start < 256; start = j + len) {
      zeta = zetas[k++];
      for(j = start; j < start + len; j++) {
        t = fqmul(zeta, r[j + len]);
        r[j + len] = r[j] - t;
        r[j] = r[j] + t;
      }
    }
  }
}

void ntt_2(int16_t r[256]) {
  unsigned int len, start, j, k;
  int16_t t, zeta;
  unsigned int zeta_index; // 用于存储查表索引

  k = 1;
  for(len = 128; len >= 2; len >>= 1) {
      for(start = 0; start < 256; start = j + len) {
          // 只有在第一轮（len=128）时才使用查表法
          if(len == 128) {
              // 保存当前zeta索引，然后k自增
              zeta_index = k;
              k++;
              
              for(j = start; j < start + len; j++) {
                  int16_t s = r[j + len];
                  
                  // 简化并检查s是否在[-3, 3]范围内
                  s = barrett_reduce(s);
                  
                  if(s >= -3 && s <= 3) {
                      // 使用预计算的表获取结果
                      t = zeta_mul_table[zeta_index][s + 3];
                      // printf("===== 触发查表加速 =====\n");
                  } else {
                      // 当s超出范围时使用常规方法
                      t = fqmul(zetas[zeta_index], s);
                  }
                  
                  // 更新结果
                  r[j + len] = r[j] - t;
                  r[j] = r[j] + t;
              }
          } else {
              // 其他轮次使用原始逻辑
              zeta = zetas[k++];
              for(j = start; j < start + len; j++) {
                  t = fqmul(zeta, r[j + len]);
                  r[j + len] = r[j] - t;
                  r[j] = r[j] + t;
              }
          }
      }
  }
}


/*************************************************
* Name:        invntt_tomont
*
* Description: Inplace inverse number-theoretic transform in Rq and
*              multiplication by Montgomery factor 2^16.
*              Input is in bitreversed order, output is in standard order
*
* Arguments:   - int16_t r[256]: pointer to input/output vector of elements of Zq
**************************************************/
void invntt(int16_t r[256]) {
  unsigned int start, len, j, k;
  int16_t t, zeta;
  const int16_t f = 1441; // mont^2/128

  k = 127;
  for(len = 2; len <= 128; len <<= 1) {
    for(start = 0; start < 256; start = j + len) {
      zeta = zetas[k--];
      for(j = start; j < start + len; j++) {
        t = r[j];
        r[j] = barrett_reduce(t + r[j + len]);
        r[j + len] = r[j + len] - t;
        r[j + len] = fqmul(zeta, r[j + len]);
      }
    }
  }

  for(j = 0; j < 256; j++)
    r[j] = fqmul(r[j], f);
}

void invntt_2(int16_t r[256]) {
  unsigned int start, len, j, k;
  int16_t t, zeta;
  const int16_t f = 1441; // mont^2/128

  k = 127;
  for(len = 2; len <= 128; len <<= 1) {
    for(start = 0; start < 256; start = j + len) {
      zeta = zetas[k--];
      for(j = start; j < start + len; j++) {
        t = r[j];
        r[j] = barrett_reduce(t + r[j + len]);
        r[j + len] = r[j + len] - t;
        r[j + len] = fqmul(zeta, r[j + len]);
      }
    }
  }

  // 1) 按原来做，乘上 f 恢复缩放因子
  for(j = 0; j < 256; j++) {
    r[j] = fqmul(r[j], f);
  }

  // 2) **退出 Montgomery 域**：每个系数再做一次 montgomery_reduce
  // montgomery_reduce(x) = x * R^{-1} mod q
  for(j = 0; j < 256; j++) {
    r[j] = montgomery_reduce((int32_t)r[j]);
  }
}


